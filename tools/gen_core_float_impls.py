def sub(text, d):
    for k in sorted(d, key=len, reverse=True):
        text = text.replace("@" + k + "@", d[k])
    assert "@" not in text, text
    return text


def indent(text, n=4):
    pad = " " * n
    return "\n".join((pad + line) if line.strip() else line for line in text.split("\n"))


def host_methods(f):
    out = []
    for name in UNARY:
        out.append(
            "pub fn %s(self) -> %s {\n    core::intrinsics::lrr_%s_math(%du32, self, 0.0_%s, 0.0_%s)\n}\n"
            % (name, f, f, OPS[name], f, f)
        )
    for name, arg in BINARY:
        out.append(
            "pub fn %s(self, %s: %s) -> %s {\n    core::intrinsics::lrr_%s_math(%du32, self, %s, 0.0_%s)\n}\n"
            % (name, arg, f, f, f, OPS[name], arg, f)
        )
    return "".join(out)


def impl_block(f):
    d = dict(PARAMS[f])
    d["F"] = f
    body = sub(CONSTS + METHODS, d) + host_methods(f)
    return "impl %s {\n%s\n}\n" % (f, indent(body.rstrip("\n")))


def main():
    out = [HEADER]
    out.append(impl_block("f32"))
    out.append(impl_block("f64"))
    print("".join(out), end="")


if __name__ == "__main__":
    main()
