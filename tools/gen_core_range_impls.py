#!/usr/bin/env python3
"""Generate crates/lrr/facade/core/range_impls.rs: the `Clone`, `Copy`,
`PartialEq`, `Eq` and `Debug` impls of the `core::ops` range types, as
ordinary Rust.

Real core derives `Clone`/`PartialEq`/`Eq` on `Range`, `RangeFrom`, `RangeTo`,
`RangeInclusive` and `RangeToInclusive` (plus `Copy` on `RangeFull`, `RangeTo`
and `RangeToInclusive`) and writes their `Debug` impls by hand
(`library/core/src/ops/range.rs`). The facade has no macros or derives, so each
impl is emitted here as ordinary source. `Debug` prints the range syntax:
`0..3`, `1..=4`, `..5`, `2..`, `..=6` and `..`; an exhausted `RangeInclusive`
appends ` (exhausted)` as core does.

Usage: python3 tools/gen_core_range_impls.py > crates/lrr/facade/core/range_impls.rs
"""

HEADER = """// `Clone`, `Copy`, `PartialEq`, `Eq` and `Debug` of the `core::ops` range types.
//
// GENERATED by tools/gen_core_range_impls.py -- edit the generator, not this
// file. Real core derives the comparison/clone impls and writes `Debug` by
// hand; the facade has no macros or derives, so each impl is ordinary source.
use crate::ops::{Range, RangeFrom, RangeFull, RangeInclusive, RangeTo, RangeToInclusive};

"""

# (type, generic?, fields, copy, debug pieces). A debug piece is either a
# literal ("..", "..=") or the name of a field to print with `Debug`.
SPECS = [
    ("RangeFull", False, [], True, ["lit:.."]),
    ("Range", True, ["start", "end"], False, ["field:start", "lit:..", "field:end"]),
    ("RangeFrom", True, ["start"], False, ["field:start", "lit:.."]),
    ("RangeTo", True, ["end"], True, ["lit:..", "field:end"]),
    (
        "RangeInclusive",
        True,
        ["start", "end", "exhausted"],
        False,
        ["field:start", "lit:..=", "field:end"],
    ),
    ("RangeToInclusive", True, ["end"], True, ["lit:..=", "field:end"]),
]

OK = "crate::result::Result::Ok(())"
ERR = "crate::result::Result::Err(e) => return crate::result::Result::Err(e),"


def clone_impl(name, generic, fields):
    if not generic:
        return f"""impl crate::clone::Clone for {name} {{
    fn clone(&self) -> {name} {{
        {name}
    }}
}}
"""
    body = "".join(
        f"            {f}: self.{f}{'' if f == 'exhausted' else '.clone()'},\n" for f in fields
    )
    return f"""impl<Idx: crate::clone::Clone> crate::clone::Clone for {name}<Idx> {{
    fn clone(&self) -> {name}<Idx> {{
        {name} {{
{body}        }}
    }}
}}
"""


def copy_impl(name, generic):
    if not generic:
        return f"impl crate::marker::Copy for {name} {{}}\n"
    return f"impl<Idx: crate::marker::Copy> crate::marker::Copy for {name}<Idx> {{}}\n"


def eq_impls(name, generic, fields):
    if not generic:
        return f"""impl crate::cmp::PartialEq for {name} {{
    fn eq(&self, _other: &{name}) -> bool {{
        true
    }}
}}
impl crate::cmp::Eq for {name} {{}}
"""
    cond = " && ".join(f"self.{f} == other.{f}" for f in fields)
    return f"""impl<Idx: crate::cmp::PartialEq> crate::cmp::PartialEq for {name}<Idx> {{
    fn eq(&self, other: &{name}<Idx>) -> bool {{
        {cond}
    }}
}}
impl<Idx: crate::cmp::Eq> crate::cmp::Eq for {name}<Idx> {{}}
"""


def debug_impl(name, generic, pieces, fields):
    head = (
        f"impl<Idx: crate::fmt::Debug> crate::fmt::Debug for {name}<Idx> {{"
        if generic
        else f"impl crate::fmt::Debug for {name} {{"
    )
    stmts = []
    for piece in pieces:
        kind, value = piece.split(":", 1)
        if kind == "lit":
            stmts.append(f'f.write_str("{value}")')
        else:
            stmts.append(f"crate::fmt::Debug::fmt(&self.{value}, f)")
    exhausted = "exhausted" in fields
    body = ""
    for i, stmt in enumerate(stmts):
        last = i == len(stmts) - 1
        if last and not exhausted:
            body += f"        {stmt}\n"
        else:
            body += f"""        match {stmt} {{
            {OK.replace('(())', '(())')} => {{}}
            {ERR}
        }}
"""
    if exhausted:
        body += f"""        if self.exhausted {{
            f.write_str(" (exhausted)")
        }} else {{
            {OK}
        }}
"""
    return f"""{head}
    fn fmt(&self, f: &mut crate::fmt::Formatter<'_>) -> crate::fmt::Result {{
{body}    }}
}}
"""


def main():
    out = [HEADER]
    for name, generic, fields, copy, pieces in SPECS:
        out.append(clone_impl(name, generic, fields))
        if copy:
            out.append(copy_impl(name, generic))
        out.append(eq_impls(name, generic, fields))
        out.append(debug_impl(name, generic, pieces, fields))
        out.append("\n")
    print("".join(out).rstrip("\n"))


if __name__ == "__main__":
    main()
