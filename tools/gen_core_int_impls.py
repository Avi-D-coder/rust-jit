HEADER = """// Inherent methods and associated constants of the primitive integer types.
//
// GENERATED by tools/gen_core_int_impls.py -- edit the generator, not this
// file. Real core writes these with `int_impl!`/`uint_impl!`; the facade does
// not expand macros, so each type's impl block is written out. The operators
// on primitive operands are the interpreter's built-in checked ones, so the
// wrapping/overflowing arithmetic goes through wider operations (or 32-bit
// halves for the 64-bit types) and `as` casts, which truncate.
use crate::num::ParseIntError;
use crate::option::Option;
use crate::result::Result;

// 64-bit wrapping arithmetic built from 32-bit halves, so no step exceeds
// 64 bits and none can overflow.
fn lrr_wadd64(a: u64, b: u64) -> u64 {
    let lo = (a & 4294967295) + (b & 4294967295);
    let hi = (a >> 32) + (b >> 32) + (lo >> 32);
    (hi << 32) | (lo & 4294967295)
}
fn lrr_wsub64(a: u64, b: u64) -> u64 {
    lrr_wadd64(a, lrr_wadd64(!b, 1))
}
fn lrr_wmul64(a: u64, b: u64) -> u64 {
    let alo = a & 4294967295;
    let ahi = a >> 32;
    let blo = b & 4294967295;
    let bhi = b >> 32;
    let cross = ((ahi * blo) & 4294967295) + ((alo * bhi) & 4294967295);
    lrr_wadd64(alo * blo, cross << 32)
}
"""


def info(name, bits, signed):
    u = "u" + name[1:]
    s = "i" + name[1:]
    if signed:
        mn, mx = -(2 ** (bits - 1)), 2 ** (bits - 1) - 1
    else:
        mn, mx = 0, 2**bits - 1
    return {
        "T": name,
        "U": u,
        "S": s,
        "N": str(bits),
        "NM1": str(bits - 1),
        "K": str(bits // 8),
        "MIN": str(mn),
        "MAX": str(mx),
        "UMAX": str(2**bits - 1),
        "TOP": str(2 ** (bits - 1)),
    }


def sub(text, d):
    for k in sorted(d, key=len, reverse=True):
        text = text.replace("@" + k + "@", d[k])
    assert "@" not in text.replace("@@", ""), text
    return text


def indent(text, n=4):
    pad = " " * n
    return "\n".join((pad + line) if line.strip() else line for line in text.split("\n"))


