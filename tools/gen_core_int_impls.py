# ----- bytes ---------------------------------------------------------------


def swap_bytes(d, bits):
    if bits == 8:
        return "pub fn swap_bytes(self) -> @T@ {\n    self\n}\n"
    return """\
pub fn swap_bytes(self) -> @T@ {
    let x = self as @U@;
    let mut r: @U@ = 0;
    let mut i: u32 = 0;
    while i < @K@ {
        r = (r << 8) | ((x >> (8 * i)) & 255);
        i += 1;
    }
    r as @T@
}
"""


def byte_conversions(bits):
    k = bits // 8
    if k == 1:
        return """\
pub fn to_be_bytes(self) -> [u8; 1] {
    [self as u8]
}
pub fn to_le_bytes(self) -> [u8; 1] {
    [self as u8]
}
pub fn to_ne_bytes(self) -> [u8; 1] {
    [self as u8]
}
pub fn from_be_bytes(bytes: [u8; 1]) -> @T@ {
    bytes[0] as @T@
}
pub fn from_le_bytes(bytes: [u8; 1]) -> @T@ {
    bytes[0] as @T@
}
pub fn from_ne_bytes(bytes: [u8; 1]) -> @T@ {
    bytes[0] as @T@
}
"""
    be = ", ".join(
        "(x >> %d) as u8" % (8 * (k - 1 - i)) if i < k - 1 else "x as u8" for i in range(k)
    )
    le = ", ".join(
        "(x >> %d) as u8" % (8 * i) if i > 0 else "x as u8" for i in range(k)
    )
    from_be = " | ".join(
        "((bytes[%d] as @U@) << %d)" % (i, 8 * (k - 1 - i)) if i < k - 1 else "(bytes[%d] as @U@)" % i
        for i in range(k)
    )
    from_le = " | ".join(
        "((bytes[%d] as @U@) << %d)" % (i, 8 * i) if i > 0 else "(bytes[0] as @U@)"
        for i in range(k)
    )
    return f"""\
pub fn to_be_bytes(self) -> [u8; {k}] {{
    let x = self as @U@;
    [{be}]
}}
pub fn to_le_bytes(self) -> [u8; {k}] {{
    let x = self as @U@;
    [{le}]
}}
pub fn to_ne_bytes(self) -> [u8; {k}] {{
    self.to_le_bytes()
}}
pub fn from_be_bytes(bytes: [u8; {k}]) -> @T@ {{
    ({from_be}) as @T@
}}
pub fn from_le_bytes(bytes: [u8; {k}]) -> @T@ {{
    ({from_le}) as @T@
}}
pub fn from_ne_bytes(bytes: [u8; {k}]) -> @T@ {{
    @T@::from_le_bytes(bytes)
}}
"""


