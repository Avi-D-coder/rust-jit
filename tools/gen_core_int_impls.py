#!/usr/bin/env python3
"""Generate crates/lrr/facade/core/int_impls.rs: the inherent methods and
associated constants of the primitive integer types, as ordinary Rust.

The facade does not expand macros, so the per-type `impl` blocks that real
core writes with `int_impl!`/`uint_impl!` are expanded here. Arithmetic uses
wider operations or 32-bit halves instead of the (panicking) operators so a
wrapping result never trips the interpreter's overflow checks; the operators
themselves stay the panicking ones where real core's debug build panics
(`pow`, `abs`, `next_power_of_two`).

Usage: python3 tools/gen_core_int_impls.py > crates/lrr/facade/core/int_impls.rs
"""

