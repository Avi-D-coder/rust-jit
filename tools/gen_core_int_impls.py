def impl_block(name, bits, signed):
    d = info(name, bits, signed)
    parts = [COMMON]
    wide = bits == 64
    if wide:
        parts.append(WIDE_SIGNED if signed else WIDE_UNSIGNED)
    else:
        parts.append(SMALL_ADD_SUB)
        parts.append(SMALL_MUL_SIGNED if signed else SMALL_MUL_UNSIGNED)
    parts.append(swap_bytes(d, bits))
    parts.append(byte_conversions(bits))
    if signed:
        parts.append(SIGNED)
        parts.append(SIGNED_MIDPOINT_WIDE if wide else SIGNED_MIDPOINT_SMALL)
        parts.append(FROM_STR_RADIX_SIGNED)
    else:
        parts.append(UNSIGNED)
        parts.append(FROM_STR_RADIX_UNSIGNED)
        if name == "u8":
            parts.append(U8_ONLY)
    body = sub("".join(parts), d)
    return "impl %s {\n%s\n}\n" % (name, indent(body.rstrip("\n")))


