#!/usr/bin/env python3
"""Generate crates/lrr/facade/core/ops_impls.rs: the operator-trait impls of
the primitive integer, float and bool types, as ordinary Rust.

Real core writes these with `add_impl!`, `forward_ref_binop!`,
`add_assign_impl!`, `neg_impl!`, `not_impl!` and friends. The facade has no
macros (its sources expand nothing at discovery), so each impl is emitted here
as ordinary source. Operators on primitive operands inside ordinary code are
the interpreter's built-in checked ones, so every body is the built-in
operator on the dereferenced operands. That gives the overflow/division panics
of a rustc debug build, and lets a generic `fn f<T: Add<Output = T>>(a: T, b:
T) -> T { a + b }` instantiated at a primitive select these impls.

Per type, each binary operator has the four by-value/by-reference forms of
`forward_ref_binop!` (`T op T`, `T op &T`, `&T op T`, `&T op &T`); each
compound assignment has `T op= T` and `T op= &T`; `Neg` (signed integers and
floats) and `Not` (integers and bool) have the value and reference forms.
Shifts cover `T << T` and the by-reference forms by default. Real core's
`shl_impl_all!`/`shr_impl_all!` cover every integer right-hand-side type
(`impl Shl<u8> for i64`, ...); `--all-shift-rhs` emits that full 12x12 matrix.
It is off by default because it roughly triples the impl count (about 2400
instead of about 840 impls), which costs roughly 2.4 s of facade preparation
per run in a debug build. Mixed-type shifts on primitive operands in ordinary
code are the interpreter's built-in operators and need no impl; the matrix only
matters for a generic `T: Shl<u32>` instantiated at a primitive.

Usage: python3 tools/gen_core_ops_impls.py > crates/lrr/facade/core/ops_impls.rs
"""

import sys

SIGNED = ["i8", "i16", "i32", "i64", "i128", "isize"]
UNSIGNED = ["u8", "u16", "u32", "u64", "u128", "usize"]
INTS = SIGNED + UNSIGNED
FLOATS = ["f32", "f64"]

# (trait, method, operator)
ARITH = [
    ("Add", "add", "+"),
    ("Sub", "sub", "-"),
    ("Mul", "mul", "*"),
    ("Div", "div", "/"),
    ("Rem", "rem", "%"),
]
BITWISE = [
    ("BitAnd", "bitand", "&"),
    ("BitOr", "bitor", "|"),
    ("BitXor", "bitxor", "^"),
]
SHIFTS = [
    ("Shl", "shl", "<<"),
    ("Shr", "shr", ">>"),
]

HEADER = """// Operator-trait impls of the primitive types.
//
// GENERATED by tools/gen_core_ops_impls.py -- edit the generator, not this
// file. Real core writes these with `add_impl!`/`forward_ref_binop!`/
// `add_assign_impl!`/`neg_impl!`/`not_impl!`; the facade has no macros, so each
// impl is ordinary source. Operators on primitive operands are the
// interpreter's built-in checked ones (a debug build's overflow and division
// panics), so each body is the built-in operator on the dereferenced operands.
use crate::ops::{
    Add, AddAssign, BitAnd, BitAndAssign, BitOr, BitOrAssign, BitXor, BitXorAssign, Div, DivAssign,
    Mul, MulAssign, Neg, Not, Rem, RemAssign, Shl, ShlAssign, Shr, ShrAssign, Sub, SubAssign,
};

"""


def binary(trait, method, op, lhs, rhs):
    """`lhs op rhs` and its three by-reference forms (forward_ref_binop!)."""
    out = f"""impl {trait}<{rhs}> for {lhs} {{
    type Output = {lhs};
    fn {method}(self, rhs: {rhs}) -> {lhs} {{
        self {op} rhs
    }}
}}
impl<'a> {trait}<&'a {rhs}> for {lhs} {{
    type Output = {lhs};
    fn {method}(self, rhs: &'a {rhs}) -> {lhs} {{
        self {op} *rhs
    }}
}}
impl<'a> {trait}<{rhs}> for &'a {lhs} {{
    type Output = {lhs};
    fn {method}(self, rhs: {rhs}) -> {lhs} {{
        *self {op} rhs
    }}
}}
impl<'a, 'b> {trait}<&'a {rhs}> for &'b {lhs} {{
    type Output = {lhs};
    fn {method}(self, rhs: &'a {rhs}) -> {lhs} {{
        *self {op} *rhs
    }}
}}
"""
    return out


def assign(trait, method, op, lhs, rhs):
    """`lhs op= rhs` and `lhs op= &rhs` (forward_ref_op_assign!)."""
    return f"""impl {trait}Assign<{rhs}> for {lhs} {{
    fn {method}_assign(&mut self, rhs: {rhs}) {{
        *self {op}= rhs;
    }}
}}
impl<'a> {trait}Assign<&'a {rhs}> for {lhs} {{
    fn {method}_assign(&mut self, rhs: &'a {rhs}) {{
        *self {op}= *rhs;
    }}
}}
"""


def unary(trait, method, op, ty):
    return f"""impl {trait} for {ty} {{
    type Output = {ty};
    fn {method}(self) -> {ty} {{
        {op}self
    }}
}}
impl<'a> {trait} for &'a {ty} {{
    type Output = {ty};
    fn {method}(self) -> {ty} {{
        {op}*self
    }}
}}
"""


def main():
    all_shift_rhs = "--all-shift-rhs" in sys.argv[1:]
    out = [HEADER]
    for ty in INTS + FLOATS:
        ops = ARITH + (BITWISE if ty in INTS else [])
        for trait, method, op in ops:
            out.append(binary(trait, method, op, ty, ty))
            out.append(assign(trait, method, op, ty, ty))
        if ty in SIGNED or ty in FLOATS:
            out.append(unary("Neg", "neg", "-", ty))
        if ty in INTS:
            out.append(unary("Not", "not", "!", ty))
            for trait, method, op in SHIFTS:
                for rhs in INTS if all_shift_rhs else [ty]:
                    out.append(binary(trait, method, op, ty, rhs))
                    out.append(assign(trait, method, op, ty, rhs))
    for trait, method, op in BITWISE:
        out.append(binary(trait, method, op, "bool", "bool"))
        out.append(assign(trait, method, op, "bool", "bool"))
    out.append(unary("Not", "not", "!", "bool"))
    print("".join(out), end="")


if __name__ == "__main__":
    main()
