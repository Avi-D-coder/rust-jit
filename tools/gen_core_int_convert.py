#!/usr/bin/env python3
"""Generate crates/lrr/facade/core/int_convert.rs: the `From`/`TryFrom` matrices
between the primitive integer types (and the lossless bool/char/float
conversions), as real core's `impl_from!`/`try_from_*` macros declare them.

The facade does not expand macro_rules, so every impl is written out. 128-bit
integers are outside the profile. Lossless `TryFrom` pairs use `Infallible`
(real core gets them from the blanket `TryFrom<U> for T where U: Into<T>`)."""
import pathlib

INTS = ["i8", "i16", "i32", "i64", "isize", "u8", "u16", "u32", "u64", "usize"]
SIGNED = {t for t in INTS if t.startswith("i")}

LOSSLESS = {
    "u8": ["u16", "u32", "u64", "usize", "i16", "i32", "i64", "isize"],
    "u16": ["u32", "u64", "usize", "i32", "i64"],
    "u32": ["u64", "i64"],
    "i8": ["i16", "i32", "i64", "isize"],
    "i16": ["i32", "i64", "isize"],
    "i32": ["i64"],
}
lossless_pairs = {(s, t) for s, ts in LOSSLESS.items() for t in ts}

out = []
w = out.append
w("// `From`/`TryFrom` between the primitive numeric types.")
w("//")
w("// GENERATED by tools/gen_core_int_convert.py -- edit the generator, not this")
w("// file. Real core writes these with `impl_from!`/`try_from_*` macros; the")
w("// facade does not expand macros, so each impl is written out.")
w("use crate::convert::{From, Infallible, TryFrom};")
w("use crate::num::TryFromIntError;")
w("use crate::result::Result;")
w("")
w("impl crate::fmt::Debug for TryFromIntError {")
w("    fn fmt(&self, f: &mut crate::fmt::Formatter<'_>) -> crate::fmt::Result {")
w('        f.write_str("TryFromIntError(())")')
w("    }")
w("}")
w("impl crate::fmt::Display for TryFromIntError {")
w("    fn fmt(&self, f: &mut crate::fmt::Formatter<'_>) -> crate::fmt::Result {")
w('        f.write_str("out of range integral type conversion attempted")')
w("    }")
w("}")
w("impl crate::clone::Clone for TryFromIntError {")
w("    fn clone(&self) -> TryFromIntError {")
w("        TryFromIntError(())")
w("    }")
w("}")
w("impl crate::cmp::PartialEq for TryFromIntError {")
w("    fn eq(&self, _other: &TryFromIntError) -> bool {")
w("        true")
w("    }")
w("}")
w("impl crate::cmp::Eq for TryFromIntError {}")
w("impl crate::fmt::Debug for Infallible {")
w("    fn fmt(&self, _f: &mut crate::fmt::Formatter<'_>) -> crate::fmt::Result {")
w("        match *self {}")
w("    }")
w("}")
w("")

def from_impl(src, dst, body):
    w(f"impl From<{src}> for {dst} {{")
    w(f"    fn from(v: {src}) -> {dst} {{")
    w(f"        {body}")
    w("    }")
    w("}")

for s, ts in LOSSLESS.items():
    for t in ts:
        from_impl(s, t, f"v as {t}")
for t in INTS + ["f32", "f64"]:
    if t in ("f32", "f64"):
        continue
    from_impl("bool", t, "if v { 1 } else { 0 }")
from_impl("u8", "char", "v as char")
from_impl("char", "u32", "v as u32")
from_impl("char", "u64", "v as u64")
from_impl("f32", "f64", "v as f64")
for s in ["i8", "i16", "u8", "u16"]:
    from_impl(s, "f32", "v as f32")
for s in ["i8", "i16", "i32", "u8", "u16", "u32"]:
    from_impl(s, "f64", "v as f64")
from_impl("bool", "f32", "if v { 1.0 } else { 0.0 }")
from_impl("bool", "f64", "if v { 1.0 } else { 0.0 }")
w("")

for s in INTS:
    for t in INTS:
        if s == t:
            continue
        if (s, t) in lossless_pairs:
            w(f"impl TryFrom<{s}> for {t} {{")
            w("    type Error = Infallible;")
            w(f"    fn try_from(v: {s}) -> Result<{t}, Infallible> {{")
            w(f"        Result::Ok(v as {t})")
            w("    }")
            w("}")
            continue
        if s not in SIGNED:
            check = f"(v as u64) <= ({t}::MAX as u64)"
        elif t in SIGNED:
            check = f"(v as i64) >= ({t}::MIN as i64) && (v as i64) <= ({t}::MAX as i64)"
        else:
            check = f"v >= 0 && (v as u64) <= ({t}::MAX as u64)"
        w(f"impl TryFrom<{s}> for {t} {{")
        w("    type Error = TryFromIntError;")
        w(f"    fn try_from(v: {s}) -> Result<{t}, TryFromIntError> {{")
        w(f"        if {check} {{")
        w(f"            Result::Ok(v as {t})")
        w("        } else {")
        w("            Result::Err(TryFromIntError(()))")
        w("        }")
        w("    }")
        w("}")

path = pathlib.Path(__file__).resolve().parent.parent / "crates/lrr/facade/core/int_convert.rs"
path.write_text("\n".join(out) + "\n")
print(path, len(out), "lines")
